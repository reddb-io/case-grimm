# KHM 151* (variant): Twelve Idle Servants
KHM_VARIANT_ATU: dict[int, str | None] = {151: "1951"}


def main():
    data = yaml.safe_load(MANIFEST.read_text(encoding="utf-8"))
    augmented = 0
    for t in data["tales"]:
        if t["kind"] != "tale":
            continue
        khm = t["khm"]
        variant = t.get("khm_variant", False)
        atu = (KHM_VARIANT_ATU if variant else KHM_ATU).get(khm)
        if atu is not None:
            t["atu"] = atu
            augmented += 1
        elif khm in KHM_ATU and KHM_ATU[khm] is None:
            t["atu"] = None  # explicit: no ATU
    MANIFEST.write_text(yaml.dump(data, sort_keys=False, allow_unicode=True, width=1000), encoding="utf-8")
    print(f"Augmented {augmented} Hunt tales with ATU codes.")


if __name__ == "__main__":
    main()
